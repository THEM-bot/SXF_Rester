export function guideOf(key) {
  const g = GUIDES[key];
  if (!g) return { title: key, body: '（该阶段暂无专门指引，参考状态机里的 goal / do）' };
  if (key === 'DONE') return g;
  return { title: g.title, body: `${g.body}\n${TASK_DISCIPLINE}\n${KB_DISCIPLINE}\n${YXT_DISCIPLINE}\n${REFLECT_DISCIPLINE}` };
}

export function guidesIndex() {
  return Object.entries(GUIDES).map(([k, v]) => `- \`${k}\` ${v.title}`);
}

