export function reflectPromptsOf(stageKey) {
  const own = BY_STAGE[stageKey] || [];
  return [...own, ...COMMON].map(([q, hint]) => ({ q, hint }));
}

export function allReflectStages() {
  return Object.keys(BY_STAGE);
}
